class VisorTerminosWidget extends StatelessWidget {
  late List<String> textoTerminos;

  VisorTerminosWidget(this.textoTerminos, {super.key});

  @override
  Widget build(BuildContext context) {
    return Container(
      color: Colors.white,
      child: ListView.separated(
        padding: const EdgeInsets.all(20),
        itemCount: textoTerminos.length,
        separatorBuilder: (context, index) =>
            const SizedBox(height: 8), // Espacio entre líneas
        itemBuilder: (context, index) {
          final linea = textoTerminos[index];
          return _construirEstiloLinea(linea);
        },
      ),
    );
  }

  /// Esta función analiza el texto y devuelve el Widget con el estilo correcto
  Widget _construirEstiloLinea(String texto) {
    // 1. TÍTULO PRINCIPAL (Mayúsculas y contiene "TÉRMINOS")
    if (texto.contains("TÉRMINOS Y CONDICIONES DE USO") ||
        texto.contains("AVISO DE PRIVACIDAD INTEGRAL")) {
      return Padding(
        padding: const EdgeInsets.only(bottom: 10),
        child: Text(
          texto,
          textAlign: TextAlign.center,
          style: TextStyle(
            fontSize: 16,
            fontWeight: FontWeight.bold,
            color: appTheme.onPrimaryContainer, // Azul corporativo
          ),
        ),
      );
    }

    // 2. ENCABEZADOS DE SECCIÓN (Ej: "1. ACEPTACIÓN...")
    // Detecta si empieza con número y punto "1."
    if (RegExp(r'^\d+\.').hasMatch(texto) && texto.toUpperCase() == texto) {
      return Padding(
        padding: const EdgeInsets.only(top: 15, bottom: 5),
        child: Text(
          texto,
          style: TextStyle(
            fontSize: 14,
            fontWeight: FontWeight.bold,
            color: appTheme.onPrimaryContainer,
          ),
        ),
      );
    }

    // 3. BULLET POINTS (Ej: "• 'Usuario'...")
    if (texto.trim().startsWith("•")) {
      return Padding(
        padding: const EdgeInsets.only(left: 10),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              "• ",
              style: TextStyle(fontWeight: FontWeight.bold, fontSize: 12),
            ),
            Expanded(
              child: Text(
                texto
                    .replaceAll("•", "")
                    .trim(), // Quitamos el punto del string
                textAlign: TextAlign.justify,
                style: TextStyle(
                  fontSize: 13,
                  color: appTheme.onPrimaryContainer,
                  height: 1.4,
                ),
              ),
            ),
          ],
        ),
      );
    }

    // 4. LISTAS NUMERADAS INTERNAS (Ej: "1. Personas interesadas...")
    // Si empieza con número pero NO está todo en mayúsculas
    if (RegExp(r'^\d+\.').hasMatch(texto) && texto.toUpperCase() != texto) {
      return Padding(
        padding: const EdgeInsets.only(left: 10, bottom: 2),
        child: Text(
          texto,
          textAlign: TextAlign.justify,
          style: TextStyle(fontSize: 13, color: Colors.grey[800], height: 1.4),
        ),
      );
    }

    // 5. TEXTO NORMAL (Párrafos)
    // Alineación justificada para look legal
    return Text(
      texto,
      textAlign: TextAlign.justify,
      style: TextStyle(
        fontSize: 13,
        color: Colors.grey[700],
        height: 1.4, // Altura de línea para legibilidad
      ),
    );
  }
}
